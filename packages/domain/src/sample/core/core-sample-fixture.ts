export function toCreateSample(sample: Sample): CreateSample {
  return {
    name: sample.name,
    nature: sample.nature,
    type: sample.type,
    material: sample.material,
    materialOtherName: sample.materialOtherName,
    texture: sample.texture,
    metamorphicFacies: sample.metamorphicFacies,
    metamorphicFabric: sample.metamorphicFabric,
    collectionMethod: sample.collectionMethod,
    collectionMethodDescription: sample.collectionMethodDescription,
    specificName: sample.specificName,
    location: sample.location,
    description: sample.description,
    condition: sample.condition,
    repository: sample.repository,
    geologicalContextDescription: sample.geologicalContextDescription,
    physiographicEnvironment: sample.physiographicEnvironment,
    scientificContext: sample.scientificContext,
    syntheticDetails: sample.syntheticDetails,
    age: sample.age,
    relations: sample.relations.map(({ id: _id, ...relation }) => relation),
    processSteps: sample.processSteps,
    security: sample.security,
    existenceStatus: sample.existenceStatus,
    availabilityStatus: sample.availabilityStatus,
    resourceType: sample.resourceType,
    economicInterestElements: sample.economicInterestElements,
    economicResourceTypePrecision: sample.economicResourceTypePrecision,
    economicDepositName: sample.economicDepositName,
    economicDepositDescription: sample.economicDepositDescription,
    manualGroupIds: sample.manualGroups.map((group) => group.id),
    parentIds: sample.parents.map((parent) => parent.id),
  };
}
